export const MARKER_START = '<!-- social-card:start -->'
export const MARKER_END = '<!-- social-card:end -->'

/** HTML-escape a value going into an attribute. The copy above contains apostrophes. */
function attr(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

/** The block of tags for one card, indented to sit where the markers are. */
export function renderSocialCard(card: SocialCard): string {
  const tags: string[] = [
    `<title>${attr(card.title)}</title>`,
    `<meta name="description" content="${attr(card.description)}" />`,
  ]

  if (!card.indexable) {
    tags.push('<meta name="robots" content="noindex" />')
  }
  if (card.url) {
    tags.push(`<link rel="canonical" href="${attr(card.url)}" />`, `<meta property="og:url" content="${attr(card.url)}" />`)
  }

  tags.push(
    '<meta property="og:type" content="website" />',
    `<meta property="og:site_name" content="${attr(DEFAULT_CARD.title)}" />`,
    `<meta property="og:title" content="${attr(card.title)}" />`,
    `<meta property="og:description" content="${attr(card.description)}" />`,
    '<meta property="og:locale" content="en_GB" />',
    `<meta property="og:image" content="${CARD_IMAGE.url}" />`,
    '<meta property="og:image:type" content="image/png" />',
    `<meta property="og:image:width" content="${CARD_IMAGE.width}" />`,
    `<meta property="og:image:height" content="${CARD_IMAGE.height}" />`,
    `<meta property="og:image:alt" content="${attr(CARD_IMAGE.alt)}" />`,
    // The one Twitter tag with no og:* fallback. summary_large_image is what makes
    // X draw the 1.91:1 image above the title instead of a small square thumbnail.
    '<meta name="twitter:card" content="summary_large_image" />',
  )

  return [MARKER_START, ...tags.map(tag => `  ${tag}`), MARKER_END].join('\n  ')
}

/**
 * Replace the marked block in a document with this card's tags.
 *
 * Throws rather than silently doing nothing: a missing marker means index.html has
 * been edited and every preview on the origin has quietly gone generic, which is a
 * failure nobody would notice from looking at the app.
 */
export function applySocialCard(html: string, card: SocialCard): string {
  const start = html.indexOf(MARKER_START)
  const end = html.indexOf(MARKER_END)
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`index.html has no ${MARKER_START} ... ${MARKER_END} block to put the link-preview tags in`)
  }
  return html.slice(0, start) + renderSocialCard(card) + html.slice(end + MARKER_END.length)
}
